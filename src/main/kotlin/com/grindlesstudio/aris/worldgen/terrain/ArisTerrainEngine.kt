package com.grindlesstudio.aris.worldgen

import kotlin.math.max
import kotlin.math.min

/**
 * Главный математический движок terrain Aris.
 *
 * На этом этапе он НЕ создаёт блоки напрямую.
 * Его задача — определить высоту поверхности в конкретной точке X/Z.
 */
object ArisTerrainEngine {

    // ============================================================
    // ОСНОВНЫЕ НАСТРОЙКИ ARIS
    // ============================================================

    /**
     * Минимальная высота terrain Aris.
     *
     * Важно:
     * это именно наша игровая граница terrain,
     * а не обязательно технический minY DimensionType.
     */
    const val MIN_TERRAIN_Y = -350

    /**
     * Максимальная высота terrain Aris.
     */
    const val MAX_TERRAIN_Y = 650

    /**
     * Уровень моря.
     */
    const val SEA_LEVEL = 0


    // ============================================================
    // ГЛАВНАЯ ФУНКЦИЯ
    // ============================================================

    /**
     * Возвращает высоту поверхности Aris
     * в координатах X/Z.
     *
     * Например:
     *
     * getSurfaceHeight(100, 200)
     *
     * может вернуть:
     *
     * 35  -> поверхность на Y=35
     * -20 -> подводная поверхность
     * 180 -> гора
     */
    fun getSurfaceHeight(x: Int, z: Int): Int {

        // --------------------------------------------------------
        // 1. Континентальный noise
        // --------------------------------------------------------
        //
        // Определяет:
        //
        // океан
        // берег
        // суша
        // --------------------------------------------------------

        val continentalness = continentalNoise(x, z)


        // --------------------------------------------------------
        // 2. Базовая высота
        // --------------------------------------------------------
        //
        // Continentalness превращаем в приблизительную высоту.
        // Пока это простая версия.
        //
        // Позже здесь появятся:
        //
        // elevation
        // mountains
        // erosion
        // rivers
        // detail
        // --------------------------------------------------------

        var height = SEA_LEVEL + continentalness


        // --------------------------------------------------------
        // 3. Горы
        // --------------------------------------------------------
        //
        // Если значение mountainNoise большое,
        // добавляем высоту.
        // --------------------------------------------------------

        val mountains = mountainNoise(x, z)

        height += mountains


        // --------------------------------------------------------
        // 4. Ограничиваем результат
        // --------------------------------------------------------
        //
        // Terrain никогда не должен выйти за:
        //
        // -350 ... 650
        // --------------------------------------------------------

        height = max(MIN_TERRAIN_Y, height)
        height = min(MAX_TERRAIN_Y, height)


        return height
    }


    // ============================================================
    // CONTINENTALNESS
    // ============================================================

    /**
     * Создаёт очень крупные области суши и океана.
     *
     * Это пока НЕ настоящий Minecraft noise.
     *
     * Это первый простой прототип нашего собственного
     * continentalness.
     */
    private fun continentalNoise(x: Int, z: Int): Int {

        /*
         * Делим координаты на большое число.
         *
         * Чем больше число:
         *
         * 500
         * 1000
         * 2000
         *
         * тем крупнее форма.
         *
         * Нам нужны огромные континенты,
         * поэтому масштаб будет большим.
         */

        val nx = x / 1500.0
        val nz = z / 1500.0


        /*
         * Простая волновая функция.
         *
         * sin/cos дают плавное изменение значения.
         *
         * Это ВРЕМЕННО.
         *
         * Позже заменим её на настоящий coherent noise
         * с seed мира.
         */

        val value =
            kotlin.math.sin(nx) *
                    kotlin.math.cos(nz)


        /*
         * Переводим диапазон примерно:
         *
         * -1 ... +1
         *
         * в высоту.
         *
         * Отрицательные значения:
         * океан
         *
         * положительные:
         * суша
         */

        return (value * 80.0).toInt()
    }


    // ============================================================
    // MOUNTAIN NOISE
    // ============================================================

    /**
     * Определяет наличие гор.
     *
     * Пока это простая функция.
     *
     * Позже здесь будет отдельная система
     * mountain chains.
     */
    private fun mountainNoise(x: Int, z: Int): Int {

        /*
         * Другой масштаб!
         *
         * Continentalness:
         * 1500 блоков
         *
         * Mountains:
         * 450 блоков
         *
         * Поэтому горы будут меняться чаще,
         * чем континенты.
         */

        val nx = x / 450.0
        val nz = z / 450.0


        val value =
            kotlin.math.sin(nx * 1.7) *
                    kotlin.math.cos(nz * 1.3)


        /*
         * Берём только положительную часть.
         *
         * Почему?
         *
         * Мы пока не хотим,
         * чтобы mountainNoise выкапывал землю.
         *
         * Он только добавляет горы.
         */

        val mountainStrength = max(0.0, value)


        /*
         * Максимальная высота гор
         * на данном первом прототипе:
         *
         * примерно 150 блоков.
         *
         * До 400+ мы дойдём позже,
         * когда появится полноценная
         * mountain-chain система.
         */

        return (mountainStrength * 150.0).toInt()
    }
}